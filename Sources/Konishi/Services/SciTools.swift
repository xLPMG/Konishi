def plot_function(expression, x_min, x_max, title=None, num_points=400):
    """Plot a single-variable function and save it as a PNG.

    Purpose:
        Since the agent cannot see a window, this renders y = f(x) to a temp PNG and
        returns a textual description (range, extrema) plus the file path.

    Args:
        expression (str): f(x) in terms of "x", using numpy as np, e.g. "np.sin(x)/x"
            or "x**2 - 3*x".
        x_min (float): Left edge of the x range.
        x_max (float): Right edge of the x range.
        title (str | None): Optional plot title.
        num_points (int): Sample count. Defaults to 400.

    Returns:
        str: JSON {"ok": true, "file_path": "...", "description": "...",
            "x_range": [..], "y_range": [..], "peak": {"x", "y"}, "trough": {"x", "y"}}.
    """
    try:
        import numpy as np
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        x = np.linspace(float(x_min), float(x_max), int(num_points))
        env = {"__builtins__": {}, "np": np, "x": x, "sin": np.sin, "cos": np.cos,
               "tan": np.tan, "exp": np.exp, "log": np.log, "sqrt": np.sqrt, "pi": np.pi}
        y = np.asarray(eval(expression, env), dtype=float)
        fig, ax = plt.subplots(figsize=(6, 4))
        ax.plot(x, y)
        ax.set_xlabel("x")
        ax.set_ylabel("y")
        ax.set_title(title or ("y = " + expression))
        ax.grid(True, alpha=0.3)
        path = _save_fig(plt, title)
        finite = np.isfinite(y)
        imax = int(np.argmax(np.where(finite, y, -np.inf)))
        imin = int(np.argmin(np.where(finite, y, np.inf)))
        desc = ("Line plot of y = %s for x in [%g, %g]. Peak y=%g at x=%g; minimum y=%g at x=%g."
                % (expression, float(x_min), float(x_max),
                   float(y[imax]), float(x[imax]), float(y[imin]), float(x[imin])))
        return _ok(file_path=path, description=desc,
                   x_range=[float(x_min), float(x_max)],
                   y_range=[float(np.nanmin(y)), float(np.nanmax(y))],
                   peak={"x": float(x[imax]), "y": float(y[imax])},
                   trough={"x": float(x[imin]), "y": float(y[imin])})
    except Exception as e:
        return _err(e)


def _install_plot_hooks():
    """Route matplotlib output into the current working directory (the conversation folder) so
    Konishi can display and store any plot the agent makes. Safe to call repeatedly."""
    try:
        import os, tempfile, atexit
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        from matplotlib.figure import Figure
    except Exception:
        return
    if getattr(plt, "_konishi_hooked", False):
        return
    plt._konishi_hooked = True
    saved = set()
    orig_savefig = Figure.savefig

    def dump(fig):
        fd, path = tempfile.mkstemp(prefix="konishi_plot_", suffix=".png", dir=os.getcwd())
        os.close(fd)
        orig_savefig(fig, path, dpi=120, bbox_inches="tight")
        saved.add(id(fig))

    def savefig(self, *a, **k):
        saved.add(id(self))
        return orig_savefig(self, *a, **k)
    Figure.savefig = savefig

    def show(*a, **k):
        for n in plt.get_fignums():
            fig = plt.figure(n)
            if id(fig) not in saved:
                dump(fig)
        return None
    plt.show = show

    def _final():
        try:
            for n in plt.get_fignums():
                fig = plt.figure(n)
                if id(fig) not in saved:
                    dump(fig)
        except Exception:
            pass
    atexit.register(_final)


