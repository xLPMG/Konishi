def solve_equation(equation, variable="x"):
    """Solve a single algebraic equation symbolically.

    Purpose:
        Find the closed-form roots of an equation with respect to one variable.

    Args:
        equation (str): The equation. Either an expression assumed equal to zero,
            e.g. "x**2 - 4", or an explicit equality, e.g. "x**2 = 4". Use Python
            power syntax ("**", not "^").
        variable (str): Name of the symbol to solve for. Defaults to "x".

    Returns:
        str: JSON. On success {"ok": true, "variable": "x", "equation": "...",
            "solutions": ["-2", "2"]}. On failure {"ok": false, "error": "..."}.
    """
    try:
        import sympy as sp
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        var = sp.symbols(variable)
        if "=" in equation:
            lhs, rhs = equation.split("=", 1)
            expr = sp.Eq(sp.sympify(lhs), sp.sympify(rhs))
        else:
            expr = sp.sympify(equation)
        solutions = sp.solve(expr, var)
        return _ok(variable=variable, equation=equation,
                   solutions=[str(s) for s in solutions])
    except Exception as e:
        return _err(e)


def differentiate(expression, variable="x", order=1):
    """Compute a symbolic derivative.

    Purpose:
        Differentiate an expression with respect to a variable, to any order.

    Args:
        expression (str): The expression, e.g. "sin(x)*x**2".
        variable (str): The differentiation variable. Defaults to "x".
        order (int): The derivative order (>= 1). Defaults to 1.

    Returns:
        str: JSON {"ok": true, "derivative": "...", "order": n} or an error.
    """
    try:
        import sympy as sp
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        var = sp.symbols(variable)
        result = sp.diff(sp.sympify(expression), var, int(order))
        return _ok(expression=expression, variable=variable, order=int(order),
                   derivative=str(sp.simplify(result)))
    except Exception as e:
        return _err(e)


def integrate_expression(expression, variable="x", lower=None, upper=None):
    """Compute a symbolic indefinite or definite integral.

    Purpose:
        Integrate an expression. If both bounds are given, evaluate the definite
        integral; otherwise return the antiderivative.

    Args:
        expression (str): The integrand, e.g. "x**2".
        variable (str): The integration variable. Defaults to "x".
        lower (str | float | None): Lower bound for a definite integral, or None.
        upper (str | float | None): Upper bound for a definite integral, or None.

    Returns:
        str: JSON with "integral" (and "definite": true/false) or an error.
    """
    try:
        import sympy as sp
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        var = sp.symbols(variable)
        integrand = sp.sympify(expression)
        if lower is not None and upper is not None:
            result = sp.integrate(integrand, (var, sp.sympify(lower), sp.sympify(upper)))
            return _ok(expression=expression, variable=variable, definite=True,
                       lower=str(lower), upper=str(upper), integral=str(result))
        result = sp.integrate(integrand, var)
        return _ok(expression=expression, variable=variable, definite=False,
                   integral=str(result) + " + C")
    except Exception as e:
        return _err(e)


