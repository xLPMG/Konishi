def matrix_svd(matrix):
    """Singular Value Decomposition of a matrix (A = U S V^T).

    Args:
        matrix (list[list[float]]): Any real matrix.

    Returns:
        str: JSON with "U", "singular_values", and "Vt", or an error.
    """
    try:
        import numpy as np
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        u, s, vt = np.linalg.svd(_as_matrix(matrix))
        return _ok(U=u.tolist(), singular_values=s.tolist(), Vt=vt.tolist())
    except Exception as e:
        return _err(e)


def solve_linear_system(A, b):
    """Solve the linear system A x = b.

    Args:
        A (list[list[float]]): Coefficient matrix (n x n).
        b (list[float]): Right-hand side vector (length n).

    Returns:
        str: JSON {"ok": true, "solution": [...]} or an error (e.g. singular system).
    """
    try:
        import numpy as np
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        return _ok(solution=np.linalg.solve(_as_matrix(A), np.array(b, dtype=float)).tolist())
    except Exception as e:
        return _err(e)


