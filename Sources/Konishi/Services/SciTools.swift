import json


def _ok(**kwargs):
    payload = {"ok": True}
    payload.update(kwargs)
    return json.dumps(payload, default=str, ensure_ascii=False)


def _err(message, hint=None):
    payload = {"ok": False, "error": str(message)}
    if hint:
        payload["hint"] = hint
    return json.dumps(payload, ensure_ascii=False)


