def data_summary(file_path):
    """Summarise a tabular dataset (CSV or JSON) with pandas.

    Purpose:
        Give the agent a compact statistical picture of a dataset: shape, dtypes,
        descriptive statistics, missing values, and numeric correlations.

    Args:
        file_path (str): Path to a .csv or .json file (absolute or ~-relative).

    Returns:
        str: JSON with "shape", "columns", "dtypes", "describe", "missing_values",
            and "correlation" (numeric columns only). Or an error.
    """
    try:
        import os
        import pandas as pd
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        path = os.path.expanduser(str(file_path))
        if not os.path.exists(path):
            return _err("File not found: " + path)
        lower = path.lower()
        if lower.endswith(".json"):
            df = pd.read_json(path)
        else:
            df = pd.read_csv(path)
        numeric = df.select_dtypes("number")
        corr = numeric.corr().round(4).to_dict() if numeric.shape[1] >= 2 else {}
        return _ok(
            shape=list(df.shape),
            columns=list(df.columns.astype(str)),
            dtypes={str(k): str(v) for k, v in df.dtypes.items()},
            describe=json.loads(df.describe(include="all").to_json()),
            missing_values={str(k): int(v) for k, v in df.isna().sum().items()},
            correlation=corr,
        )
    except Exception as e:
        return _err(e)


