    except Exception as e:
        return _err(e)


def solve_ode(rhs, y0, t_start, t_end, num_points=200):
    """Numerically integrate a first-order ODE system with scipy.solve_ivp.

    Purpose:
        Solve dy/dt = f(t, y) as an initial value problem. Supports a single ODE
        or a coupled system.

    Args:
        rhs (str | list[str]): Right-hand side expression(s) in terms of "t" and the
            state components "y0", "y1", ... (indexed to match y0). Example single:
            "-0.5*y0". Example system (predator-prey): ["y0 - 0.1*y0*y1",
            "-1.5*y1 + 0.075*y0*y1"]. numpy is available as np (e.g. "np.sin(t)").
        y0 (float | list[float]): Initial state value(s) at t_start.
        t_start (float): Start time.
        t_end (float): End time.
        num_points (int): Number of evenly spaced output samples. Defaults to 200.

    Returns:
        str: JSON with "t" and "y" (downsampled to <= 50 points each), "final_state",
            and per-component "min"/"max". Errors return {"ok": false, ...}.
    """
    try:
        import numpy as np
        from scipy.integrate import solve_ivp
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        exprs = [rhs] if isinstance(rhs, str) else list(rhs)
        y0_list = [y0] if isinstance(y0, (int, float)) else [float(v) for v in y0]
        safe = {"np": np, "sin": np.sin, "cos": np.cos, "tan": np.tan,
                "exp": np.exp, "log": np.log, "sqrt": np.sqrt, "pi": np.pi, "abs": abs}

        def f(t, y):
            env = dict(safe)
            env["t"] = t
            env["y"] = y
            for i, val in enumerate(y):
                env["y%d" % i] = val
            return [float(eval(e, {"__builtins__": {}}, env)) for e in exprs]

        t_eval = np.linspace(float(t_start), float(t_end), int(num_points))
        sol = solve_ivp(f, (float(t_start), float(t_end)), y0_list, t_eval=t_eval, rtol=1e-8, atol=1e-10)
        if not sol.success:
            return _err("Integration failed: " + str(sol.message))
        step = max(1, len(sol.t) // 50)
        t_ds = sol.t[::step].tolist()
        y_ds = [row[::step].tolist() for row in sol.y]
        return _ok(components=len(y0_list),
                   t=t_ds, y=y_ds,
                   final_state=[float(row[-1]) for row in sol.y],
                   min=[float(row.min()) for row in sol.y],
                   max=[float(row.max()) for row in sol.y])
    except Exception as e:
        return _err(e)


def _as_matrix(matrix):
    import numpy as np
    return np.array(matrix, dtype=float)


def matrix_eigen(matrix):
    """Eigenvalue / eigenvector decomposition of a square matrix.

    Args:
        matrix (list[list[float]]): A square matrix as nested lists.

    Returns:
        str: JSON with "eigenvalues" (list; complex shown as "a+bj") and
            "eigenvectors" (columns), or an error.
    """
    try:
        import numpy as np
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        a = _as_matrix(matrix)
        if a.ndim != 2 or a.shape[0] != a.shape[1]:
            return _err("Matrix must be square.")
        vals, vecs = np.linalg.eig(a)
        return _ok(eigenvalues=[str(v) for v in vals],
                   eigenvectors=[[str(x) for x in col] for col in vecs.T.tolist()])
    except Exception as e:
        return _err(e)


def matrix_inverse(matrix):
    """Invert a square matrix.

    Args:
        matrix (list[list[float]]): A square, non-singular matrix.

    Returns:
        str: JSON {"ok": true, "inverse": [[...], ...]} or an error (e.g. singular).
    """
    try:
        import numpy as np
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        a = _as_matrix(matrix)
        return _ok(inverse=np.linalg.inv(a).tolist())
    except Exception as e:
        return _err(e)


def matrix_determinant(matrix):
    """Determinant of a square matrix.

    Args:
        matrix (list[list[float]]): A square matrix.

    Returns:
        str: JSON {"ok": true, "determinant": float} or an error.
    """
