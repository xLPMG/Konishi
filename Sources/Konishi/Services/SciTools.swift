def arxiv_search(query, max_results=5):
    """Search arXiv and return the most relevant papers.

    Args:
        query (str): A search query, e.g. "diffusion models for protein folding".
        max_results (int): Number of papers to return. Defaults to 5.

    Returns:
        str: JSON {"ok": true, "count": n, "papers": [{"title", "authors",
            "summary", "pdf_url", "arxiv_id", "published"}, ...]} or an error.
    """
    try:
        import arxiv
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        search = arxiv.Search(query=query, max_results=int(max_results),
                              sort_by=arxiv.SortCriterion.Relevance)
        try:
            results = list(arxiv.Client().results(search))
        except Exception:
            results = list(search.results())
        papers = []
        for r in results:
            papers.append({
                "title": r.title,
                "authors": [a.name for a in r.authors],
                "summary": (r.summary or "").strip(),
                "pdf_url": r.pdf_url,
                "arxiv_id": r.get_short_id(),
                "published": str(getattr(r, "published", "")),
            })
        return _ok(count=len(papers), papers=papers)
    except Exception as e:
        return _err(e)


def arxiv_metadata(arxiv_id):
    """Fetch detailed metadata for one arXiv paper by ID.

    Args:
        arxiv_id (str): An arXiv identifier, e.g. "2307.09288" or "1706.03762v5".

    Returns:
        str: JSON with title, authors, summary, pdf_url, categories, primary_category,
            comment, doi, journal_ref, published, and updated. Or an error.
    """
    try:
        import arxiv
    except ImportError as e:
        return _err(e, hint=_MISSING_HINT)
    try:
        search = arxiv.Search(id_list=[str(arxiv_id)])
        try:
            results = list(arxiv.Client().results(search))
        except Exception:
            results = list(search.results())
        if not results:
            return _err("No paper found for id " + str(arxiv_id))
        r = results[0]
        return _ok(
            arxiv_id=r.get_short_id(),
            title=r.title,
            authors=[a.name for a in r.authors],
            summary=(r.summary or "").strip(),
            pdf_url=r.pdf_url,
            categories=list(getattr(r, "categories", [])),
            primary_category=getattr(r, "primary_category", None),
            comment=getattr(r, "comment", None),
            doi=getattr(r, "doi", None),
            journal_ref=getattr(r, "journal_ref", None),
            published=str(getattr(r, "published", "")),
            updated=str(getattr(r, "updated", "")),
        )
    except Exception as e:
        return _err(e)


