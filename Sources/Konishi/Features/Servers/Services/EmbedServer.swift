def _pool(outputs, attention_mask):
    # Prefer the library's per-architecture pooled + normalized embedding.
    embs = getattr(outputs, "text_embeds", None)
    if embs is not None:
        return embs
    # Fallback: masked mean pool + L2 normalize.
    hidden = outputs.last_hidden_state
    mask = attention_mask[..., None].astype(hidden.dtype)
    summed = (hidden * mask).sum(axis=1)
